#!/usr/bin/env python3
"""Generate gallery docs summaries from the component registry metadata."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATE = ROOT / "cvkg-gallery" / "src" / "state.rs"
OUTPUT = ROOT / "cvkg-gallery" / "src" / "generated_docs.rs"

ENTRY = re.compile(
    r'ComponentMeta::new\(\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]*)"',
    re.S,
)


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    entries = {}
    for name, category, description in ENTRY.findall(STATE.read_text()):
        entries[name] = f"{category} — {description}"

    lines = [
        "// @generated by scripts/generate_gallery_docs.py — do not edit by hand.",
        "",
        "/// Metadata-backed summary for one registered component.",
        "pub fn summary(name: &str) -> Option<&'static str> {",
        "    match name {",
    ]
    for name in sorted(entries):
        lines.append(f"        {rust_string(name)} => Some({rust_string(entries[name])}),")
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
        "/// Whether a generated summary exists for `name`.",
        "pub fn has_summary(name: &str) -> bool {",
        "    summary(name).is_some()",
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {len(entries)} summaries to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
