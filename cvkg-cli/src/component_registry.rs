//! Generated component source registry for `cvkg-cli component`.

use serde::Deserialize;
use std::path::{Path, PathBuf};

/// One component entry in the generated manifest.
#[derive(Clone, Debug, Deserialize, PartialEq)]
pub struct ComponentEntry {
    pub name: String,
    pub path: String,
    pub category: String,
}

#[derive(Deserialize)]
struct Manifest {
    version: u32,
    components: Vec<ComponentEntry>,
}

/// Source-backed registry of CVKG components.
pub struct ComponentRegistry {
    pub entries: Vec<ComponentEntry>,
}

impl ComponentRegistry {
    /// Load the manifest generated by `scripts/generate_component_manifest.py`.
    pub fn load_default() -> Result<Self, String> {
        let manifest: Manifest = serde_json::from_str(include_str!("../manifest.json"))
            .map_err(|error| format!("invalid component manifest: {error}"))?;
        if manifest.version != 1 {
            return Err(format!("unsupported manifest version {}", manifest.version));
        }
        Ok(Self {
            entries: manifest.components,
        })
    }

    /// Return the canonical source text for one component.
    pub fn source(&self, name: &str) -> Option<String> {
        let entry = self.entries.iter().find(|entry| entry.name == name)?;
        std::fs::read_to_string(workspace_root().join(&entry.path)).ok()
    }

    /// Return true when a local copy matches the canonical source.
    pub fn matches_local(&self, name: &str, local: &Path) -> Option<bool> {
        let canonical = self.source(name)?;
        let local_text = std::fs::read_to_string(local).ok()?;
        Some(canonical == local_text)
    }

    /// Copy a component source into `target_dir` and return the new path.
    pub fn add(&self, name: &str, target_dir: &Path) -> Result<PathBuf, String> {
        let source = self
            .source(name)
            .ok_or_else(|| format!("unknown component: {name}"))?;
        let entry = self
            .entries
            .iter()
            .find(|entry| entry.name == name)
            .expect("source implies entry");
        let file_name = Path::new(&entry.path)
            .file_name()
            .ok_or_else(|| format!("invalid source path for {name}"))?;
        let target = target_dir.join(file_name);
        if target.exists() {
            return Err(format!("target already exists: {}", target.display()));
        }
        std::fs::write(&target, source)
            .map_err(|error| format!("cannot write {}: {error}", target.display()))?;
        Ok(target)
    }

    /// Refresh a local copy from the canonical source. Returns true if changed.
    pub fn update(&self, name: &str, local: &Path) -> Result<bool, String> {
        let source = self
            .source(name)
            .ok_or_else(|| format!("unknown component: {name}"))?;
        if std::fs::read_to_string(local).ok().as_deref() == Some(source.as_str()) {
            return Ok(false);
        }
        std::fs::write(local, source)
            .map_err(|error| format!("cannot write {}: {error}", local.display()))?;
        Ok(true)
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("cvkg-cli sits inside the workspace")
        .to_path_buf()
}
